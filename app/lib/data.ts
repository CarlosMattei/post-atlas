export const queue = posts
  .filter(
    (post) =>
      post.status === "aprovado" &&
      post.scheduledAt === null &&
      post.linkedinPostId === null,
  )
  .sort((a, b) => {
    if (a.manualOrder !== null || b.manualOrder !== null) {
      return (a.manualOrder ?? Number.MAX_SAFE_INTEGER) -
        (b.manualOrder ?? Number.MAX_SAFE_INTEGER);
    }
    const scoreDiff = effectiveScoreValue(b) - effectiveScoreValue(a);
    return scoreDiff !== 0
      ? scoreDiff
      : new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime();
  });

function effectiveScoreValue(post: Post): number {
  return post.scoreOverride ?? post.aiScore ?? 0;
}
